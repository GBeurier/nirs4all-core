#!/usr/bin/env python3
"""Generate host-embedded execution-profile data from compat/capabilities.toml.

``compat/capabilities.toml`` is the single owner of the versioned execution
profiles. This script validates the registry and emits the same JSON payload as
embedded constants for every distributable host (Python, JavaScript/WASM, Rust,
MATLAB/Octave) plus the sibling R package when its checkout is present, so no
host needs the TOML file or a sibling checkout at runtime.

    python3.11 scripts/generate_capability_profiles.py            # rewrite
    python3.11 scripts/generate_capability_profiles.py --check    # drift gate

``--check`` fails (exit 1) on any drift or registry inconsistency. Missing optional
R or Web checkouts report ``unavailable``. ``--require-r`` and ``--require-web``
instead fail when their target checkout is missing.

The default rewrite generates the Core and R outputs only and skips the Web
snapshot even when a Web checkout is present. Writing the Web snapshot needs the
explicit ``--include-web`` opt-in, which is reserved for an authorized joint
frontend batch with the maintainer; passing the flag is not itself that
authorization. ``--check`` always verifies the Web snapshot when present.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - local Python < 3.11 fallback
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parents[1]
TOML_PATH = ROOT / "compat/capabilities.toml"
SOURCE_LABEL = "compat/capabilities.toml"

CANONICAL_JSON = "tests/parity/expected/capability_profiles.json"
PYTHON_TARGET = "bindings/python/src/nirs4all_core/_capability_profiles.py"
WASM_TARGET = "bindings/wasm/src/capability-profiles.js"
RUST_TARGET = "bindings/rust/nirs4all/src/capability_profiles_data.rs"
MATLAB_TARGET = "bindings/matlab/+nirs4all/executionProfilesJson.m"
R_TARGET = "R/execution_profiles_data.R"
WEB_TARGET = "web-app/src/engine/core-execution-profiles.generated.ts"

HEADER = "Generated by scripts/generate_capability_profiles.py from compat/capabilities.toml. Do not edit."


class RegistryError(ValueError):
    """The TOML registry is internally inconsistent."""


def load_registry(path: Path = TOML_PATH) -> dict[str, Any]:
    return tomllib.loads(path.read_text(encoding="utf-8"))


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise RegistryError(message)


CANONICAL_PROFILE = "native-n4a-canonical"
# Owner-neutral storage of arbitrary opaque members: it reads, writes and updates bytes and executes nothing.
STORAGE_PROFILE = "n4a-container"
NATIVE_PACKAGE_PROFILE = "native-methods-package"
SUPPORTED_PROFILES = ("native-workflow", "native-conformal", NATIVE_PACKAGE_PROFILE, CANONICAL_PROFILE, STORAGE_PROFILE)
PROFILE_VERSION = 1
# The canonical V1 `.n4a` actions. They are declared only by the canonical profile; the
# envelope/V2 profiles declare them as explicit unsupported cells. Conversely the canonical
# profile declares the envelope/V2 operations unsupported: none of them is an alias.
CANONICAL_OPERATIONS = ("produce", "inspect", "calibrate", "retrain")
NON_CANONICAL_OPERATIONS = ("compile", "fit", "import", "export")
# Declared by the storage profile only; its `inspect` is the owner-neutral view of any container.
STORAGE_ONLY_OPERATIONS = ("read", "write", "update")
STORAGE_OPERATIONS = ("inspect", *STORAGE_ONLY_OPERATIONS)


ROUTE_KINDS = ("public_return", "cli_response", "archive_transfer")
ROUTE_CARRIES = {"public_return": ("host_object",), "cli_response": ("wrapper_json",), "archive_transfer": ("native_archive_v2",)}
ROUTE_OPERATIONS = ("fit", "import", "export")


def _validate_routes(pid: str, item: dict[str, Any], ops_out: dict[str, Any]) -> list[dict[str, Any]]:
    """Content is declared per operation, surface and route; nothing is a global assumption."""

    routes = [dict(route) for route in item["content_routes"]]
    schemas = {content["schema"] for content in item["content_types"]}
    seen = set()
    for route in routes:
        where = f"{pid} route {route.get('operation')}/{route.get('surface')}/{route.get('route')}"
        _require(route.get("route") in ROUTE_KINDS, f"{where}: bad route kind")
        cell = ops_out.get(route["operation"], {}).get(route["surface"])
        _require(cell is not None and cell["status"] == "supported", f"{where}: operation/surface is not supported")
        _require(route["entrypoint"] in {entry["symbol"] for entry in cell["entrypoints"]}, f"{where}: entrypoint is not a supported public entrypoint")
        key = (route["operation"], route["surface"], route["route"])
        _require(key not in seen, f"{where}: duplicate route")
        seen.add(key)
        carries = route["carries"]
        if route["route"] == "cli_response":
            allowed = {"wrapper_json"}
        elif route["route"] == "public_return":
            allowed = {"host_object", "wrapper_json"}
        else:
            allowed = {"native_archive_v2"}
        _require(carries in allowed, f"{where}: {carries} cannot travel on this route")
        if "schema" in route:
            _require(route["schema"] in schemas, f"{where}: schema is not a declared content type")
            _require(carries in ("wrapper_json", "host_object"), f"{where}: an archive carries no wrapper schema id")
        if carries == "native_archive_v2":
            _require(route.get("archive_schema_version") == 2 and route.get("calibration_in_archive") and route.get("mechanism"), f"{where}: archive facts incomplete")
            _require("fields" not in route and "schema" not in route, f"{where}: archive transfer declares no fields or schema id")
        else:
            _require(route.get("fields") and all(isinstance(f, str) and f for f in route["fields"]), f"{where}: fields required")
            _require("schema" not in route["fields"], f"{where}: the schema id is its own key, not a field")
        if route["route"] == "cli_response":
            _require(bool(route.get("cli_command")), f"{where}: cli_command required")
    if routes:
        for operation in ROUTE_OPERATIONS:
            for surface, cell in ops_out[operation].items():
                if cell["status"] == "supported":
                    _require(any(r["operation"] == operation and r["surface"] == surface for r in routes),
                             f"{pid}.{operation}.{surface}: supported operation declares no content route")
    return routes


def _validate_operation_groups(pid: str, ops_out: dict[str, Any]) -> None:
    """Keep the canonical V1 actions and the envelope/V2 operations apart; no operation aliases another."""

    if pid == STORAGE_PROFILE:
        for operation, row in ops_out.items():
            if operation in STORAGE_OPERATIONS:
                _require(any(cell["status"] == "supported" for cell in row.values()),
                         f"{pid}.{operation}: at least one surface must declare a real entrypoint")
                continue
            for surface, cell in row.items():
                _require(cell["status"] == "unsupported", f"{pid}.{operation}.{surface}: storage executes nothing; {operation} belongs to another profile")
        return
    for operation in STORAGE_ONLY_OPERATIONS:
        for surface, cell in ops_out[operation].items():
            _require(cell["status"] == "unsupported", f"{pid}.{operation}.{surface}: {operation} is declared only by {STORAGE_PROFILE}")
    if pid != CANONICAL_PROFILE:
        for operation in CANONICAL_OPERATIONS:
            for surface, cell in ops_out[operation].items():
                _require(cell["status"] == "unsupported", f"{pid}.{operation}.{surface}: canonical V1 actions are declared only by {CANONICAL_PROFILE}")
        return
    for operation in NON_CANONICAL_OPERATIONS:
        for surface, cell in ops_out[operation].items():
            _require(cell["status"] == "unsupported", f"{pid}.{operation}.{surface}: {operation} is not a canonical V1 action and must not alias one")
    owners: dict[tuple[str, str], str] = {}
    for operation, row in ops_out.items():
        for surface, cell in row.items():
            for entry in cell.get("entrypoints", []):
                key = (surface, entry["symbol"])
                _require(owners.setdefault(key, operation) == operation,
                         f"{pid}: {surface} symbol {entry['symbol']} cannot serve both {owners[key]} and {operation}")
    for operation in ("produce", "inspect", "predict", "retrain"):
        _require(any(cell["status"] == "supported" for cell in ops_out[operation].values()),
                 f"{pid}.{operation}: at least one surface must declare a real entrypoint")


def build_payload(caps: dict[str, Any]) -> dict[str, Any]:
    """Validate the registry and return the shared host payload."""

    meta = caps["execution_profiles"]
    surfaces = list(caps["runtime_surfaces"])
    operations = list(meta["operations"])
    statuses = set(meta["statuses"])
    profiles_in = caps["execution_profile"]
    ids = [item["id"] for item in profiles_in]
    _require(tuple(ids) == SUPPORTED_PROFILES, f"supported profile set must be exactly {SUPPORTED_PROFILES}, found {tuple(ids)}")
    _require(meta["version"] == 1, "registry version must be 1")

    profiles: list[dict[str, Any]] = []
    for item in profiles_in:
        pid = item["id"]
        _require(item["version"] == PROFILE_VERSION, f"{pid}: version must be {PROFILE_VERSION}")
        _require(set(item["surfaces"]) <= set(surfaces), f"{pid}: surfaces outside runtime_surfaces")
        _require(bool(item["content_types"]), f"{pid}: content_types must not be empty")
        requirements = {surface: list(rows) for surface, rows in item["runtime_requirements"].items()}
        _require(set(requirements) == set(item["surfaces"]), f"{pid}: runtime_requirements must name exactly the profile surfaces")
        _require(all(rows and all(isinstance(row, str) and row for row in rows) for rows in requirements.values()),
                 f"{pid}: every surface needs non-empty runtime requirements")
        for content in item["content_types"]:
            _require(set(content) == {"schema", "owner", "carried_in"}, f"{pid}: content type fields")

        ops_in = item["operations"]
        _require(set(ops_in) == set(operations), f"{pid}: operations must be exactly {operations}")
        ops_out: dict[str, Any] = {}
        for operation in operations:
            row = ops_in[operation]
            _require(set(row) == set(surfaces), f"{pid}.{operation}: every runtime surface needs an entry")
            ops_out[operation] = {}
            for surface in surfaces:
                cell = row[surface]
                _require(cell["status"] in statuses, f"{pid}.{operation}.{surface}: bad status")
                if cell["status"] == "supported":
                    _require(surface in item["surfaces"], f"{pid}.{operation}.{surface}: supported outside profile surfaces")
                    _require(bool(cell.get("entrypoints")), f"{pid}.{operation}.{surface}: supported needs entrypoints")
                    _require("reason" not in cell, f"{pid}.{operation}.{surface}: supported must not carry a reason")
                    out = {"status": "supported", "entrypoints": [dict(e) for e in cell["entrypoints"]]}
                else:
                    _require(bool(cell.get("reason")), f"{pid}.{operation}.{surface}: unsupported needs a reason")
                    _require("entrypoints" not in cell, f"{pid}.{operation}.{surface}: unsupported must not list entrypoints")
                    out = {"status": "unsupported", "reason": cell["reason"]}
                ops_out[operation][surface] = out
        for surface in item["surfaces"]:
            _require(
                any(ops_out[op][surface]["status"] == "supported" for op in operations),
                f"{pid}: surface {surface} declares no supported operation",
            )
        _validate_operation_groups(pid, ops_out)
        routes = _validate_routes(pid, item, ops_out)
        profiles.append({
            "id": pid,
            "version": item["version"],
            "title": item["title"],
            "surfaces": list(item["surfaces"]),
            "dependencies": list(item["dependencies"]),
            "runtime_requirements": requirements,
            "content_types": [dict(content) for content in item["content_types"]],
            "content_routes": routes,
            "operations": ops_out,
            "limits": list(item["limits"]),
        })

    federation: list[dict[str, Any]] = []
    for item in caps["external_federation"]:
        _require(item["surface"] not in surfaces, f"{item['surface']}: external surface must not be a Core runtime surface")
        _require(item["core_runtime_surface"] is False, f"{item['surface']}: core_runtime_surface must be false")
        _require(tuple(item["profiles"]) == SUPPORTED_PROFILES, f"{item['surface']}: federates exactly the supported profiles")
        for entry in item["entrypoints"]:
            _require(entry["profile"] in item["profiles"], f"{item['surface']}: entrypoint profile not federated")
            _require(entry["operation"] in operations, f"{item['surface']}: bad entrypoint operation")
            if entry["profile"] == STORAGE_PROFILE:
                _require(entry["operation"] in STORAGE_OPERATIONS,
                         f"{item['surface']}: {entry['operation']} is not a storage operation of {STORAGE_PROFILE}")
                continue
            _require(entry["operation"] not in STORAGE_ONLY_OPERATIONS,
                     f"{item['surface']}: {entry['operation']} is declared only by {STORAGE_PROFILE}")
            _require(entry["profile"] == CANONICAL_PROFILE or entry["operation"] not in CANONICAL_OPERATIONS,
                     f"{item['surface']}: {entry['operation']} is a canonical V1 action, not an operation of {entry['profile']}")
            _require(entry["profile"] != CANONICAL_PROFILE or entry["operation"] not in NON_CANONICAL_OPERATIONS,
                     f"{item['surface']}: {entry['operation']} must not alias a canonical V1 action")
        federation.append({
            "surface": item["surface"],
            "repository": item["repository"],
            "package": item["package"],
            "core_runtime_surface": False,
            "status": item["status"],
            "profiles": list(item["profiles"]),
            "contracts": list(item["contracts"]),
            "evidence": list(item["evidence"]),
            "entrypoints": [dict(e) for e in item["entrypoints"]],
            "note": item["note"],
        })

    return {
        "schema": meta["schema"],
        "version": meta["version"],
        "generated_from": SOURCE_LABEL,
        "runtime_surfaces": surfaces,
        "operations": operations,
        "statuses": list(meta["statuses"]),
        "limits": list(meta["limits"]),
        "profiles": profiles,
        "external_federation": federation,
    }


def canonical_text(payload: dict[str, Any]) -> str:
    return json.dumps(payload, indent=2, ensure_ascii=True) + "\n"


def _lines(text: str) -> list[str]:
    return text.splitlines(keepends=True)


def render_python(text: str) -> str:
    body = "".join(f"    {json.dumps(line)},\n" for line in _lines(text))
    return (
        f'"""{HEADER}"""\n\n'
        "from __future__ import annotations\n\n"
        "_EXECUTION_PROFILES_LINES: tuple[str, ...] = (\n"
        f"{body})\n\n"
        'EXECUTION_PROFILES_JSON: str = "".join(_EXECUTION_PROFILES_LINES)\n'
    )


def render_wasm(text: str) -> str:
    return (
        f"// {HEADER}\n\n"
        "function deepFreeze(value) {\n"
        "  if (value && typeof value === 'object' && !Object.isFrozen(value)) {\n"
        "    Object.freeze(value);\n"
        "    for (const child of Object.values(value)) deepFreeze(child);\n"
        "  }\n"
        "  return value;\n"
        "}\n\n"
        f"export const executionProfilesData = deepFreeze({text.rstrip()});\n"
    )


def render_rust(text: str) -> str:
    return (
        f"// {HEADER}\n\n"
        "pub(crate) const EXECUTION_PROFILES_JSON: &str = r######\"\n"
        f"{text}\"######;\n"
    )


def render_matlab(text: str) -> str:
    rows = []
    for line in _lines(text):
        rows.append("lines{end + 1} = '" + line.rstrip("\n").replace("'", "''") + "';")
    body = "\n".join(rows)
    return (
        "function json = executionProfilesJson()\n"
        f"%EXECUTIONPROFILESJSON {HEADER}\n"
        "lines = {};\n"
        f"{body}\n"
        "json = strjoin(lines, char(10));\n"
        "end\n"
    )


def render_r(text: str) -> str:
    body = ",\n".join(f"  {json.dumps(line.rstrip(chr(10)))}" for line in _lines(text))
    return (
        f"# {HEADER}\n"
        "# Core's execution-profile registry, embedded so no sibling checkout is needed at runtime.\n"
        ".nirs4all_execution_profiles_lines <- c(\n"
        f"{body}\n"
        ")\n"
    )


def render_web(text: str) -> str:
    digest = hashlib.sha256(text.rstrip("\n").encode("utf-8")).hexdigest()
    body = ",\n".join(f"  {json.dumps(line.rstrip(chr(10)))}" for line in _lines(text))
    return (
        f"// {HEADER}\n"
        "// Metadata DEFINITION snapshot of the Core execution-profile registry. It is not\n"
        "// installed-runtime certification: the numerical shim staged in vendor/ is pinned\n"
        "// separately and this file says nothing about what that package exports.\n"
        f"export const CORE_EXECUTION_PROFILES_SOURCE = {json.dumps(SOURCE_LABEL)}\n"
        f"export const CORE_EXECUTION_PROFILES_SHA256 = {json.dumps(digest)}\n"
        "export const CORE_EXECUTION_PROFILES_JSON = [\n"
        f"{body},\n"
        "].join('\\n')\n"
    )


def targets(
    payload: dict[str, Any], r_root: Path | None, web_root: Path | None = None
) -> dict[str, tuple[Path, str]]:
    text = canonical_text(payload)
    out = {
        "canonical": (ROOT / CANONICAL_JSON, text),
        "python": (ROOT / PYTHON_TARGET, render_python(text)),
        "wasm": (ROOT / WASM_TARGET, render_wasm(text)),
        "rust": (ROOT / RUST_TARGET, render_rust(text)),
        "matlab": (ROOT / MATLAB_TARGET, render_matlab(text)),
    }
    if r_root is not None:
        out["r"] = (r_root / R_TARGET, render_r(text))
    if web_root is not None:
        out["web"] = (web_root / WEB_TARGET, render_web(text))
    return out


def default_r_root() -> Path | None:
    candidate = ROOT.parent / "nirs4all-r"
    return candidate if (candidate / "DESCRIPTION").exists() else None


def default_web_root() -> Path | None:
    candidate = ROOT.parent / "nirs4all-web"
    return candidate if (candidate / "web-app/package.json").exists() else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    parser.add_argument("--r-root", type=Path, default=None, help="nirs4all-r checkout (default: sibling directory)")
    parser.add_argument("--no-r", action="store_true", help="skip the optional R target")
    parser.add_argument("--web-root", type=Path, default=None, help="nirs4all-web checkout (default: sibling directory)")
    parser.add_argument("--no-web", action="store_true", help="skip the optional Web snapshot target")
    parser.add_argument(
        "--include-web",
        action="store_true",
        help="also WRITE the Web snapshot (opt-in, reserved for an authorized joint frontend batch; not itself that authorization; --check always checks Web)",
    )
    parser.add_argument("--require-r", action="store_true", help="fail before writing when the R target is unavailable")
    parser.add_argument("--require-web", action="store_true", help="fail before writing when the Web target is unavailable")
    args = parser.parse_args(argv)

    if args.include_web and args.no_web:
        print("--include-web and --no-web are contradictory; nothing written", file=sys.stderr)
        return 2
    if args.require_web and not args.check and not args.include_web:
        print(
            "--require-web in write mode needs --include-web: the default write skips the Web snapshot "
            "(reserved for an authorized joint frontend batch); nothing written",
            file=sys.stderr,
        )
        return 2

    try:
        payload = build_payload(load_registry())
    except (RegistryError, KeyError) as error:
        print(f"registry error: {error}", file=sys.stderr)
        return 1

    r_root = None if args.no_r else (args.r_root or default_r_root())
    web_root = None if args.no_web else (args.web_root or default_web_root())
    if r_root is not None and not (r_root / "DESCRIPTION").is_file():
        r_root = None
    if web_root is not None and not (web_root / "web-app/package.json").is_file():
        web_root = None
    missing = [name for name, required, root in (("r", args.require_r, r_root), ("web", args.require_web, web_root)) if required and root is None]
    if missing:
        print(f"required target unavailable: {', '.join(missing)} (no checkout found or target disabled); nothing written", file=sys.stderr)
        return 2
    drift = 0
    drifted: list[str] = []
    for name, (path, content) in targets(payload, r_root, web_root).items():
        if name == "web" and not args.check and not args.include_web:
            print(f"skipped     web: {path} (default write skips Web; --include-web is reserved for an authorized joint frontend batch)")
            continue
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            print(f"ok          {name}: {path}")
        elif args.check:
            print(f"DRIFT       {name}: {path}")
            drift += 1
            drifted.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"written     {name}: {path}")
    if r_root is None:
        print("unavailable r: no nirs4all-r checkout found (optional target, not a failure)")
    if web_root is None:
        print("unavailable web: no nirs4all-web checkout found (optional target, not a failure)")
    if drift:
        web_drift = "web" in drifted
        print(f"{drift} generated target(s) drifted; rerun without --check", file=sys.stderr)
        if web_drift:
            print("web drift is not fixed by the default write; it needs --include-web in an authorized joint frontend batch", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
